"""Unlabelled human-review tasks, fixed before the new model experiment."""
from __future__ import annotations
import re
import random


def plan(root):
    def section(source,heading):
        text=(root/'examples/sample_docs'/source).read_text(encoding='utf-8')
        m=re.search(r'(?m)^## '+re.escape(heading)+r'\n',text)
        if not m: raise ValueError(heading)
        nxt=re.search(r'(?m)^## ',text[m.end():])
        return {'source':source,'text':text[m.start():m.end()+nxt.start() if nxt else len(text)].strip()}
    sets=[
      ('pto','Я штатный сотрудник со стажем 4 года. Сколько дней отпуска начисляется?',
       section('hr_timeoff.md','Оплачиваемый отпуск (PTO)'),
       ['При таком стаже начисляется 23 дня оплачиваемого отпуска в год.',
        'Остаток отпуска сверх 40 дней можно сохранить, если согласен руководитель.']),
      ('refund','Исправный NW-100 вскрыт, клиент передумал и возвращает его через 12 дней после доставки.',
       section('refund_policy.md','Возврат оборудования'),
       ['При этом возврате обратную доставку оплачивает клиент.',
        'Сбор за повторное складирование здесь равен 5 процентам.']),
      ('flight','Мой перелёт длится ровно 6 часов. Директор согласен на бизнес-класс.',
       section('travel_expenses.md','Перелёты и такси'),
       ['При этих условиях бизнес-класс допускается по указанному правилу.',
        'Если перелёт длится 7 часов, одобрение директора для бизнес-класса не нужно.']),
      ('remote','Я полностью удалённый сотрудник. Хочу получить компенсацию интернета и оборудование.',
       section('remote_work.md','Компенсации'),
       ['При таком формате работы интернет компенсируется в размере 3000 рублей в месяц.',
        'Монитор можно заменить на новый каждые два года.']),
      ('purchase','Нужно внести предоплату 70 процентов новому поставщику.',
       section('procurement.md','Оплата'),
       ['Для этой предоплаты требуется согласие финансового директора.',
        'Если финансовый директор согласен, предоплата больше 50 процентов сама по себе не нарушает это правило.']),
      ('access','Я руководитель. Пользуюсь системой, которая поддерживает MFA.',
       section('security_policy.md','Управление доступом'),
       ['В описанной ситуации я обязан использовать MFA.',
        'Для доступа к продакшену достаточно согласия владельца системы на словах, заявку можно не оформлять.']),
      ('trial','Я главный инженер и ещё не завершил испытательный срок.',
       section('onboarding.md','Доступы'),
       ['При этих условиях доступ к продакшен-системам ещё не должен быть выдан.',
        'После окончания испытательного срока продакшен-доступ выдаётся автоматически без общей процедуры.']),
      ('robot','Нужно проверить характеристики NW-200 для нового проекта.',
       section('product_specs.md','Манипулятор NW-200 (промышленный уровень)'),
       ['Грузоподъёмность этой модели составляет 18 кг, гарантия — 3 года.',
        'NW-200 можно эксплуатировать при температуре минус 40 градусов.'])]
    claims=[{'private_id':f'{name}_{i}','kind':'claim','question':q,'claim':claim,
             'sources':[src]} for name,q,src,cs in sets for i,claim in enumerate(cs)]
    arms=['anchor_free','score_free','score_units']
    rng=random.Random(20261104)
    rng.shuffle(arms)
    answers=[{'private_id':cid,'kind':'answer','case_id':cid,'arm':arms[i%3]}
             for i,cid in enumerate(['q04','q08','q13','q23','q35','q38','hop03','hop08'])]
    items=claims+answers
    rng.shuffle(items)
    return [{'review_id':f'R{i+1:02d}',**item} for i,item in enumerate(items)]
